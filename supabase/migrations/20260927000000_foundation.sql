-- ---------------------------------------------------------------- tickets

create table if not exists public.tickets (
  id uuid primary key default gen_random_uuid(),
  app_id uuid not null references public.apps(id) on delete restrict,
  display_number integer generated by default as identity (start with 4801),
  customer_email text not null,
  customer_name text,
  subject text,
  status text not null default 'new'
    check (status in ('new','researching','needs_decision','executing','closed','action_failed','waiting_on_customer','snoozed','manual','auto_pending')),
  resolution text
    check (resolution is null or resolution in ('approved','approved_with_edits','rejected','handled_manually','auto','marked_done','closed_no_reply')),
  case_type text,
  case_confidence real check (case_confidence is null or (case_confidence >= 0 and case_confidence <= 1)),
  risk_level text not null default 'none' check (risk_level in ('none','high','safety')),
  risk_reason text,
  due_date date,
  stage smallint not null default 1 check (stage in (1, 2)),
  waiting_for text,
  snoozed_until timestamptz,
  tags text[] not null default '{}',
  instaradar_user_id text,
  stripe_customer_id text,
  customer_context jsonb,
  first_message_at timestamptz,
  last_message_at timestamptz,
  last_customer_message_at timestamptz,
  closed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (app_id, display_number)
);

create index if not exists tickets_status_idx on public.tickets (app_id, status);
create index if not exists tickets_customer_email_idx on public.tickets (lower(customer_email));
create index if not exists tickets_closed_at_idx on public.tickets (closed_at desc) where status = 'closed';
create index if not exists tickets_snoozed_until_idx on public.tickets (snoozed_until) where status = 'snoozed';

create trigger tickets_set_updated_at before update on public.tickets
  for each row execute function public.set_updated_at();

