-- Maelle foundation schema (IRDR-454).
-- Table names are binding. Other tickets add columns and tables in their own migrations, additive only.
-- Status-like columns are text with CHECK constraints (not enums) so later migrations can extend them
-- with a single `alter table … drop constraint / add constraint`.

create extension if not exists pgcrypto;

-- ---------------------------------------------------------------- auth allow-list

create table if not exists public.allowed_users (
  email text primary key check (email = lower(email)),
  created_at timestamptz not null default now()
);

comment on table public.allowed_users is 'The only emails that may sign in. Filled from ALLOWED_USER_EMAIL by pnpm db:migrate.';

create or replace function public.is_allowed_user()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.allowed_users a
    where a.email = lower(coalesce(auth.jwt() ->> 'email', ''))
  );
$$;

revoke all on function public.is_allowed_user() from public;
grant execute on function public.is_allowed_user() to authenticated, anon, service_role;

-- Reject any sign-up that is not on the allow-list, before the auth row exists.
create or replace function public.enforce_allowed_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.email is null or not exists (
    select 1 from public.allowed_users a where a.email = lower(new.email)
  ) then
    raise exception 'Sign-in is not allowed for this email' using errcode = '42501';
  end if;
  return new;
end;
$$;

drop trigger if exists enforce_allowed_user on auth.users;
create trigger enforce_allowed_user
  before insert on auth.users
  for each row execute function public.enforce_allowed_user();

-- ---------------------------------------------------------------- helpers

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

