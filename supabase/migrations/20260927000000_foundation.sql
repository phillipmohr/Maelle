-- ---------------------------------------------------------------- RLS: only the allowed user (service role bypasses)

do $$
declare
  t text;
begin
  foreach t in array array[
    'allowed_users','apps','tickets','messages','agent_runs','proposals','proposed_actions',
    'action_executions','decisions','release_notifications','cancellation_reasons','settings',
    'autonomy_modes','action_locks'
  ] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists allowed_user_all on public.%I', t);
    execute format(
      'create policy allowed_user_all on public.%I for all to authenticated using (public.is_allowed_user()) with check (public.is_allowed_user())',
      t
    );
  end loop;
end $$;

-- ---------------------------------------------------------------- Realtime on tickets, agent_runs, action_executions

do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'tickets') then
      alter publication supabase_realtime add table public.tickets;
    end if;
    if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'agent_runs') then
      alter publication supabase_realtime add table public.agent_runs;
    end if;
    if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'action_executions') then
      alter publication supabase_realtime add table public.action_executions;
    end if;
  end if;
end $$;

