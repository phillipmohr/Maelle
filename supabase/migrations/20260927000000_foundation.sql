  id uuid primary key default gen_random_uuid(),
  ticket_id uuid not null references public.tickets(id) on delete cascade,
  run_id uuid references public.agent_runs(id) on delete set null,
  version integer not null,
  case_type text not null,
  confidence real,
  candidate_cases jsonb not null default '[]'::jsonb,
  summary_line text not null,
  meta_line text,
  risk_level text not null default 'none' check (risk_level in ('none','high','safety')),
  risk_reason text,
  due_date date,
  customer_confirmation_needed boolean not null default false,
  stage smallint not null default 1 check (stage in (1, 2)),
  research jsonb not null default '[]'::jsonb,
  research_warnings text[] not null default '{}',
  policy_warnings text[] not null default '{}',
  conclusion text,
  -- { template, templateNotionPageId, to, subject, body, attachments: [{ name, storagePath, contentType, sizeBytes }] }
